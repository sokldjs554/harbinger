# 약신호 단어 — 피처 추출(features/text.py)에서 쓰는 렉시콘과 일부러 100 % 겹치지 않게 했다.
# (렉시콘이 생성 템플릿을 그대로 베끼면 평가가 과대 추정된다.)


def make_memo(
    rng: np.random.Generator,
    observed: dict[str, int],
    weak_items: list[str],
    diligence: float,
    prev_memo: str | None,
    copy_paste: bool,
) -> str:
    """관측 결과(0/1/2)·약신호 항목·점검자 성향으로 메모를 만든다."""
    if copy_paste:
        if prev_memo and rng.random() < 0.7:
            return prev_memo
        return str(rng.choice(LAZY))

    parts: list[str] = []
    # 주의/불량 항목 서술
    for item, level in observed.items():
        if level == 2 and rng.random() < 0.92:
            parts.append(str(rng.choice(PHRASES[item][2])))
        elif level == 1 and rng.random() < 0.75 + 0.2 * diligence:
            parts.append(str(rng.choice(PHRASES[item][1])))
    # 약신호: 체크는 양호지만 성실한 점검자가 느낀 것
    for item in weak_items:
        if rng.random() < 0.35 + 0.55 * diligence:
            parts.append(str(rng.choice(PHRASES[item][0])))
    if not parts:
        parts.append(str(rng.choice(NORMAL)))
    elif rng.random() < 0.25:
        parts.append(str(rng.choice(NORMAL[:4])))
    if rng.random() < 0.15 + 0.2 * diligence:
        parts.append(str(rng.choice(CHORES)))
    # 성실하지 않을수록 짧게
    max_len = 1 if diligence < 0.35 else (2 if diligence < 0.7 else 3)
    parts = parts[: max(1, max_len)]
    sep = str(rng.choice([", ", ". ", " / ", " "]))
    memo = sep.join(parts)
    if rng.random() < 0.3:
        memo += "."
    return memo
